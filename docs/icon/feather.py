"""Generates LiteCode's icon: a feather filled with horizontal lines of code.

The feather's outline is diagonal; the lines inside it are horizontal, as text
is, and the quill's spine splits each one. A few tokens are tinted like syntax
highlighting.
"""
import math, sys

CX, CY = 512, 520                 # feather centre
ANGLE = math.radians(-50)         # spine direction (up and to the right)
LENGTH = 700                      # spine length covered by the vane
LINE_GAP, THICK = 54, 28          # code line spacing and thickness
SPINE_CLEAR = 22                  # gap each side of the spine
W, P, A, M, B = "#FFFFFF", "#DCD5FF", "#FFD27A", "#7CF0C8", "#9CC8FF"
# Token cuts per line (fractions of the run) and tint per token, so the lines
# look like statements rather than stripes. Deterministic, hand-tuned.
TOKENS = [
    [(0, .55, W), (.68, 1, A)],
    [(0, 1, W)],
    [(0, .35, W), (.47, 1, P)],
    [(0, .7, W), (.8, 1, M)],
    [(0, 1, P)],
    [(0, .45, W), (.57, 1, B)],
    [(0, 1, W)],
    [(0, .6, P), (.72, 1, A)],
    [(0, 1, W)],
    [(0, .5, W), (.62, 1, M)],
    [(0, 1, P)],
    [(0, 1, W)],
]

ux, uy = math.cos(ANGLE), math.sin(ANGLE)   # along the spine
vx, vy = -uy, ux                              # across it

def half_width(u):
    """Vane half-width at distance u along the spine (−L/2 … L/2): a feather
    that's broad in the upper middle and narrows to a tip and a quill."""
    t = (u + LENGTH / 2) / LENGTH
    if not 0 <= t <= 1:
        return -1
    return 205 * math.sin(math.pi * t ** 0.8) ** 0.7

def runs(y):
    """Horizontal runs of the feather at height y, split by the spine."""
    out, cur = [], None
    for x in range(100, 925):
        dx, dy = x - CX, y - CY
        u, v = dx * ux + dy * uy, dx * vx + dy * vy
        side = 1 if v > 0 else -1
        inside = half_width(u) > 0 and SPINE_CLEAR < abs(v) < half_width(u) * (1 if side > 0 else 0.78)
        key = side if inside else None
        if key != (cur[0] if cur else None):
            if cur:
                out.append(cur)
            cur = [key, x, x] if key else None
        elif cur:
            cur[2] = x
    if cur:
        out.append(cur)
    return [(a, b) for k, a, b in out if b - a > THICK * 0.6]

def mark(mono=None):
    shapes, line = [], 0
    y = CY - 330
    while y < CY + 330:
        for a, b in runs(y):
            # Rounded caps add THICK/2 each side; keep them inside the outline,
            # and skip runs too short to read as a line.
            a, b = a + THICK / 2, b - THICK / 2
            if b - a < THICK * 1.2:
                continue
            toks = TOKENS[line % len(TOKENS)]
            if b - a < THICK * 4:
                toks = [(0, 1, toks[0][2])]  # too short to split into tokens
            for i, (s, e, color) in enumerate(toks):
                x1, x2 = a + (b - a) * s, a + (b - a) * e
                # A visible gap between tokens: caps plus 10 units of air.
                if i > 0:
                    x1 += THICK / 2 + 5
                if i < len(toks) - 1:
                    x2 -= THICK / 2 + 5
                if x2 - x1 < 2:
                    continue
                shapes.append(f'<line x1="{x1:.1f}" y1="{y}" x2="{x2:.1f}" y2="{y}" stroke="{mono or color}" '
                              f'stroke-width="{THICK}" stroke-linecap="round"/>')
            line += 1
        y += LINE_GAP
    # Spine from the quill's point through the tip.
    sx, sy = CX - ux * (LENGTH / 2 + 70), CY - uy * (LENGTH / 2 + 70)
    ex, ey = CX + ux * (LENGTH / 2 - 10), CY + uy * (LENGTH / 2 - 10)
    shapes.append(f'<line x1="{sx:.1f}" y1="{sy:.1f}" x2="{ex:.1f}" y2="{ey:.1f}" stroke="{mono or W}" '
                  f'stroke-width="20" stroke-linecap="round"/>')
    return "\n    ".join(shapes)

def icon():
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- LiteCode app icon: a feather filled with lines of code. Generated by docs/icon/feather.py. -->
  <defs>
    <linearGradient id="tile" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#A493FF"/>
      <stop offset="0.55" stop-color="#6E58F2"/>
      <stop offset="1" stop-color="#3F2DB8"/>
    </linearGradient>
    <radialGradient id="shine" cx="0.25" cy="0.15" r="0.75">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.35"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>
    </radialGradient>
    <filter id="lift" x="-30%" y="-30%" width="160%" height="160%">
      <feDropShadow dx="0" dy="14" stdDeviation="18" flood-color="#1B1050" flood-opacity="0.5"/>
    </filter>
  </defs>
  <rect x="64" y="64" width="896" height="896" rx="216" fill="url(#tile)"/>
  <rect x="64" y="64" width="896" height="896" rx="216" fill="url(#shine)"/>
  <rect x="65.5" y="65.5" width="893" height="893" rx="214.5" fill="none" stroke="#FFFFFF" stroke-opacity="0.18" stroke-width="3"/>
  <g filter="url(#lift)">
    {mark()}
  </g>
</svg>
'''

def mono():
    """One-color version for in-app use: Giode draws icons in one color. The
    viewBox is the mark's own square bounds, so it fills the box it's given."""
    import re
    body = mark("#FFFFFF")
    nums = [list(map(float, m)) for m in re.findall(r'x1="([\d.-]+)" y1="([\d.-]+)" x2="([\d.-]+)" y2="([\d.-]+)"', body)]
    xs = [v for n in nums for v in (n[0], n[2])]
    ys = [v for n in nums for v in (n[1], n[3])]
    pad = THICK / 2 + 4
    x0, x1, y0, y1 = min(xs) - pad, max(xs) + pad, min(ys) - pad, max(ys) + pad
    side = max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    vb = f"{cx - side/2:.0f} {cy - side/2:.0f} {side:.0f} {side:.0f}"
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{side:.0f}" height="{side:.0f}" viewBox="{vb}">
    {body}
</svg>
'''

# Usage: python3 docs/icon/feather.py assets/icon.svg assets/icons/brand.svg
# then: node docs/icon/render.js assets/icon.svg <dir>, and copy its 1024 and
# 256 px PNGs to assets/icon.png and assets/icon-256.png.
if __name__ == "__main__":
    open(sys.argv[1], "w").write(icon())
    open(sys.argv[2], "w").write(mono())
